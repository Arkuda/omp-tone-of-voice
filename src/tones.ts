const TONE_IDS: readonly string[] = ["technical", "roast", "gopnik", "sweetheart"];

export function isToneId(value: unknown): value is ToneId {
	return typeof value === "string" && TONE_IDS.includes(value);
}

export function isToneSetting(value: unknown): value is ToneSetting {
	return value === "off" || isToneId(value);
}

export function toneLabel(tone: ToneId): string {
	const entry = TONES.find((candidate) => candidate.id === tone);
	if (!entry) throw new Error(`Неизвестный тон: ${String(tone)}`);
	return entry.label;
}

/** Возвращает новый массив `[...base, block]`; исходный массив не изменяется. */
export function withTone(base: readonly string[], tone: ToneId): string[] {
	const entry = TONES.find((candidate) => candidate.id === tone);
	if (!entry) throw new Error(`Неизвестный тон: ${String(tone)}`);
	const block = `<tone-of-voice mode="${entry.id}">\n${entry.instruction}\n</tone-of-voice>`;
	return [...base, block];
}
